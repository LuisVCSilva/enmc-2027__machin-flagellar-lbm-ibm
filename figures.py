def figure_01(
    machin: dict[str, np.ndarray],
    output_directory: Path,
):

    chi = machin["chi"]

    amplitude = machin["F_abs"]

    phase = machin["F_phase"]

    fig, ax1 = plt.subplots(
        figsize=(7.2, 4.8),
    )

    line1 = ax1.plot(
        chi,
        amplitude,
        linewidth=2.0,
        label=r"$|F(\chi)|$",
    )

    ax1.set_xlabel(
        r"$\chi=s/\ell$"
    )

    ax1.set_ylabel(
        r"$|F(\chi)|$"
    )

    ax1.set_xlim(
        np.min(chi),
        np.max(chi),
    )

    ax1.set_ylim(
        0.0,
        1.05,
    )

    ax1.grid(
        True,
        alpha=0.25,
    )

    ax2 = ax1.twinx()

    line2 = ax2.plot(
        chi,
        phase,
        linestyle="--",
        linewidth=1.8,
        label=r"$\arg F(\chi)$",
    )

    ax2.set_ylabel(
        r"$\arg F(\chi)$ [rad]"
    )

    lines = line1 + line2

    labels = [
        line.get_label()
        for line in lines
    ]

    ax1.legend(
        lines,
        labels,
        loc="best",
        frameon=False,
    )

    fig.tight_layout()

    save_figure(
        fig,
        output_directory,
        "Fig01_Machin_amplitude_phase",
    )


