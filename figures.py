def figure_04(
    history: dict[str, np.ndarray],
    output_directory: Path,
):
    """
    Temporal evolution of the main LBM-IBM diagnostics.

    Panels
    ------
    (a) Filament-tip displacement.
    (b) Filament-tip velocity/kinematic diagnostic.
    (c) Maximum/mean velocity and Mach number.
    (d) Density deviations from the reference state rho = 1.
    """

    # ------------------------------------------------------------------------
    # Time
    # ------------------------------------------------------------------------

    time = np.asarray(
        history["time"],
        dtype=float,
    )

    # ------------------------------------------------------------------------
    # Helper for column names
    # ------------------------------------------------------------------------

    def get_column(
        data,
        candidates,
        required=True,
    ):
        for name in candidates:
            if name in data:
                return np.asarray(
                    data[name],
                    dtype=float,
                )

        if required:
            raise KeyError(
                "None of the following columns were found:\n"
                + ", ".join(candidates)
            )

        return None

    # ------------------------------------------------------------------------
    # Kinematics
    # ------------------------------------------------------------------------

    tip_y = get_column(
        history,
        [
            "tip_y",
            "h_tip",
        ],
    )

    tip_yy = get_column(
        history,
        [
            "tip_yy",
            "vy_tip",
            "tip_velocity",
        ],
    )

    # ------------------------------------------------------------------------
    # Flow diagnostics
    # ------------------------------------------------------------------------

    max_speed = get_column(
        history,
        [
            "max_speed",
            "u_max",
        ],
    )

    mean_speed = get_column(
        history,
        [
            "mean_speed",
            "u_mean",
        ],
        required=False,
    )

    mach = get_column(
        history,
        [
            "Mach",
            "mach",
            "Ma",
        ],
        required=False,
    )

    # ------------------------------------------------------------------------
    # Density
    # ------------------------------------------------------------------------

    rho_min = get_column(
        history,
        [
            "rho_min",
        ],
    )

    rho_max = get_column(
        history,
        [
            "rho_max",
        ],
    )

    delta_rho_min = (
        rho_min - 1.0
    )

    delta_rho_max = (
        rho_max - 1.0
    )

    # ------------------------------------------------------------------------
    # Figure
    # ------------------------------------------------------------------------

    fig, axes = plt.subplots(
        2,
        2,
        figsize=(7.2, 6.2),
        sharex=True,
    )

    ax1, ax2, ax3, ax4 = axes.ravel()

    # =========================================================================
    # (a) Tip displacement
    # =========================================================================

    ax1.plot(
        time,
        tip_y,
        linewidth=1.6,
        label=r"$y_{\mathrm{tip}}$",
    )

    ax1.set_ylabel(
        r"$y_{\mathrm{tip}}$"
    )

    ax1.set_title(
        "(a) Filament-tip displacement",
        loc="left",
    )

    ax1.grid(
        True,
        alpha=0.25,
    )

    ax1.legend(
        frameon=False,
        loc="best",
    )

    # =========================================================================
    # (b) Tip kinematics
    # =========================================================================

    ax2.plot(
        time,
        tip_yy,
        linewidth=1.6,
        label=r"$v_{\mathrm{tip}}$",
    )

    ax2.set_ylabel(
        r"$v_{\mathrm{tip}}$"
    )

    ax2.set_title(
        "(b) Filament-tip velocity",
        loc="left",
    )

    ax2.grid(
        True,
        alpha=0.25,
    )

    ax2.legend(
        frameon=False,
        loc="best",
    )

    # =========================================================================
    # (c) Flow diagnostics
    # =========================================================================

    ax3.plot(
        time,
        max_speed,
        linewidth=1.5,
        label=r"$|\mathbf{u}|_{\max}$",
    )

    if mean_speed is not None:

        ax3.plot(
            time,
            mean_speed,
            linewidth=1.5,
            linestyle="--",
            label=r"$\langle|\mathbf{u}|\rangle$",
        )

    if mach is not None:

        ax3.plot(
            time,
            mach,
            linewidth=1.5,
            linestyle=":",
            label=r"$Ma$",
        )

    ax3.set_xlabel(
        r"$t$"
    )

    ax3.set_ylabel(
        "Flow diagnostic",
    )

    ax3.set_title(
        "(c) Flow velocity and Mach number",
        loc="left",
    )

    ax3.grid(
        True,
        alpha=0.25,
    )

    ax3.legend(
        frameon=False,
        loc="best",
    )

    # =========================================================================
    # (d) Density variation
    # =========================================================================

    ax4.plot(
        time,
        delta_rho_min,
        linewidth=1.5,
        label=r"$\rho_{\min}-1$",
    )

    ax4.plot(
        time,
        delta_rho_max,
        linewidth=1.5,
        linestyle="--",
        label=r"$\rho_{\max}-1$",
    )

    ax4.axhline(
        0.0,
        linewidth=0.8,
        linestyle=":",
    )

    ax4.set_xlabel(
        r"$t$"
    )

    ax4.set_ylabel(
        r"$\Delta\rho$"
    )

    ax4.set_title(
        "(d) Density variation",
        loc="left",
    )

    ax4.grid(
        True,
        alpha=0.25,
    )

    ax4.ticklabel_format(
        axis="y",
        style="sci",
        scilimits=(-3, 3),
    )

    ax4.legend(
        frameon=False,
        loc="best",
    )

    # ------------------------------------------------------------------------
    # Common x-axis
    # ------------------------------------------------------------------------

    for ax in axes.ravel():

        ax.set_xlim(
            np.min(time),
            np.max(time),
        )

        ax.tick_params(
            which="both",
            direction="in",
        )

    # ------------------------------------------------------------------------
    # Layout
    # ------------------------------------------------------------------------

    fig.tight_layout(
        h_pad=1.4,
        w_pad=1.4,
    )

    save_figure(
        fig,
        output_directory,
        "Fig04_LBM_history",
    )
