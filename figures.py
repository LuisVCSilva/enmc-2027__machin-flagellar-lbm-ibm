def figure_07(
    field: dict[str, np.ndarray],
    output_directory: Path,
):

    x = field["x"]

    y = field["y"]

    rho = field["rho"]

    ux = field["ux"]

    uy = field["uy"]

    vorticity = field["vorticity"]

    unique_x = np.unique(x)

    unique_y = np.unique(y)

    Nx = unique_x.size

    Ny = unique_y.size

    if Nx * Ny != rho.size:
        raise ValueError(
            "final_field.csv does not contain a complete rectangular grid."
        )

    X = x.reshape(
        Ny,
        Nx,
    )

    Y = y.reshape(
        Ny,
        Nx,
    )

    RHO = rho.reshape(
        Ny,
        Nx,
    )

    U = ux.reshape(
        Ny,
        Nx,
    )

    V = uy.reshape(
        Ny,
        Nx,
    )

    WZ = vorticity.reshape(
        Ny,
        Nx,
    )

    fig, ax = plt.subplots(
        figsize=(8.0, 4.8),
    )

    image = ax.pcolormesh(
        X,
        Y,
        RHO,
        shading="auto",
    )

    cbar = fig.colorbar(
        image,
        ax=ax,
    )

    cbar.set_label(
        r"$\rho$"
    )

    # Sparse velocity field for visual reference.
    stride_x = max(
        1,
        Nx // 30,
    )

    stride_y = max(
        1,
        Ny // 15,
    )

    ax.quiver(
        X[::stride_y, ::stride_x],
        Y[::stride_y, ::stride_x],
        U[::stride_y, ::stride_x],
        V[::stride_y, ::stride_x],
        angles="xy",
        scale_units="xy",
        scale=0.02,
        width=0.002,
    )

    ax.set_xlabel(
        r"$x$"
    )

    ax.set_ylabel(
        r"$y$"
    )

    ax.set_aspect(
        "equal",
        adjustable="box",
    )

    ax.grid(
        False,
    )

    fig.tight_layout()

    save_figure(
        fig,
        output_directory,
        "Fig07_LBM_density",
    )


