# ============================================================================

def figure_03(
    kinematics: dict[str, np.ndarray],
    output_directory: Path,
):

    steps = kinematics["step"]

    markers = kinematics["marker"]

    x = kinematics["x"]

    y = kinematics["y"]

    unique_steps = np.unique(
        steps
    )

    if unique_steps.size == 0:
        raise ValueError(
            "No temporal data found for Fig. 03."
        )

    # Four representative phases.
    phase_steps = [
        unique_steps[0],
        unique_steps[
            unique_steps.size // 4
        ],
        unique_steps[
            unique_steps.size // 2
        ],
        unique_steps[
            (3 * unique_steps.size) // 4
        ],
    ]

    fig, axes = plt.subplots(
        2,
        2,
        figsize=(7.2, 6.0),
        sharex=True,
        sharey=True,
    )

    axes = axes.ravel()

    for ax, step in zip(
        axes,
        phase_steps,
    ):

        mask = (
            steps == step
        )

        order = np.argsort(
            markers[mask]
        )

        xx = x[mask][order]

        yy = y[mask][order]

        time = (
            kinematics["time"][mask][0]
        )

        ax.plot(
            xx,
            yy,
            linewidth=2.0,
        )

        ax.axhline(
            np.mean(yy),
            linestyle=":",
            linewidth=0.8,
        )

        ax.set_title(
            rf"$t/T={time / kinematics['period'][mask][0]:.2f}$"
        )

        ax.grid(
            True,
            alpha=0.2,
        )

    axes[0].set_ylabel(
        r"$y$"
    )

    axes[2].set_ylabel(
        r"$y$"
    )

    axes[2].set_xlabel(
        r"$x$"
    )

    axes[3].set_xlabel(
        r"$x$"
    )

    fig.tight_layout()

    save_figure(
        fig,
        output_directory,
        "Fig03_Machin_waveforms",
    )


