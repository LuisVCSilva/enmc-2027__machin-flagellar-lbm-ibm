# ============================================================================
# SAVE FIGURE
# ============================================================================

def save_figure(
    fig,
    output_directory: Path,
    filename: str,
):

    pdf_file = (
        output_directory
        / f"{filename}.pdf"
    )

    png_file = (
        output_directory
        / f"{filename}.png"
    )

    fig.savefig(
        pdf_file,
        bbox_inches="tight",
    )

    fig.savefig(
        png_file,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(fig)


